/**
 * Специальные типы блоков (ROADMAP §6): пульсирующий, пружинный, ватный,
 * крутящийся, дрейфующий и парный телепорт «чёрная дыра».
 * Данные блока живут в поле `Block.sp`, константы балансировки — здесь.
 */

export interface BlockSpecial {
  /** Защитные очки брони, поглощаемые до основного HP. */
  armor?: number
  /** Исходный запас брони: нужен для отображения снятых внешних колец. */
  armorMax?: number
  /** Цепной взрыв: радиус мировых единиц и урон соседям. */
  brittle?: { radius: number; damage: number }
  /** Цикл активной/неактивной физики. */
  phase?: { period: number; active: number; offset: number }
  /** Мягкое притяжение шара за пределами хитбокса. */
  magnet?: { radius: number; force: number }
  /** Пульсация: масштаб rx/ry по синусоиде вокруг базовых размеров. */
  pulse?: { freq: number; ph: number; rx0: number; ry0: number }
  /** Пружинный: удар временно разгоняет шар. */
  spring?: boolean
  /** Ватный: удар временно замедляет шар. */
  cotton?: boolean
  /** Крутящийся: угловая скорость (рад/с), гасится трением. */
  rotVel?: number
  /** Стабильное направление визуальных стрелок крутящегося блока. */
  rotDir?: 1 | -1
  /** Дрейф по маршруту: горизонталь / вертикаль / окружность. */
  drift?: { kind: "h" | "v" | "circle"; amp: number; freq: number; ph: number }
  /** Телепорт: общий id пары; переброс шара в блок с тем же id. */
  portalId?: number
  /** Кулдаун телепорта пары (сек) — против зацикливания. */
  portalCd?: number
}

/** Амплитуда пульсации размера (доля от базовых rx/ry). */
export const PULSE_AMPLITUDE = 0.22
/** Множитель скорости шара под эффектом пружины. */
export const SPRING_SPEED_MULT = 1.3
/** Время действия разгона пружины, сек. */
export const SPRING_TIME = 2.2
/** Множитель скорости шара под эффектом ваты. */
export const COTTON_SPEED_MULT = 0.5
/** Время действия замедления ваты, сек. */
export const COTTON_TIME = 2.0
/** Кулдаун пары порталов после прыжка, сек. */
export const PORTAL_CD = 1.1
/** Угловой импульс крутящегося блока от удара в край (рад/с). */
export const SPIN_KICK = 3.2
/** Предел угловой скорости крутящегося блока (рад/с). */
export const SPIN_MAX = 6
/** Перед разрушением крутящийся блок эффектно вращается одну секунду. */
export const SPIN_DEATH_DURATION = 1
/** Максимальная амплитуда маршрута в радиусах соответствующей оси блока. */
export const DRIFT_MAX_RADIUS_MULT = 3
/** Радиус цепной хрупкости относительно размера исходного блока. */
export const BRITTLE_RADIUS_MULT = 2.5
/** Максимальное число соседей одной цепной реакции (помимо источника). */
export const BRITTLE_CHAIN_MAX = 12
/** Период фазового блока по умолчанию (сек). */
export const PHASE_PERIOD = 3.2
/** Доля активной фазы. */
export const PHASE_ACTIVE_FRACTION = 0.62
/** Радиус действия магнитного блока относительно размера блока. */
export const BLOCK_MAGNET_RADIUS_MULT = 4
/** Ускорение магнитного поля в мировых единицах/сек². */
export const BLOCK_MAGNET_FORCE = 2200
