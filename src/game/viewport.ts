/**
 * Эталонное разрешение и единый масштаб мира.
 *
 * Логика движка считает координаты в «мировых единицах», привязанных к
 * эталонному окну 1920×1080. Реальное окно получает коэффициент масштаба
 * по диагонали, и канвас рисует весь мир одним трансформом — поэтому размеры
 * и скорости всех сущностей одинаковы на телефоне, FHD и 4K, а подстройка
 * баланса под конкретные экраны не нужна.
 */
import { clamp } from "./utils"

/** Эталонное окно: в этих размерах мир рисуется с масштабом 1. */
export const REF_W = 1920
export const REF_H = 1080
export const REF_DIAG = Math.hypot(REF_W, REF_H)

/** Границы масштаба: ниже 0.4 объекты неразличимы, выше 3 — гигантские. */
export const MIN_SCALE = 0.4
export const MAX_SCALE = 3

/** Единый масштаб мира: диагональ окна относительно эталонной диагонали. */
export function computeScale(cssW: number, cssH: number): number {
  return clamp(Math.hypot(cssW, cssH) / REF_DIAG, MIN_SCALE, MAX_SCALE)
}
